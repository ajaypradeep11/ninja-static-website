let activeIssue = "003";
let activeCategory = "all";
const grid = document.querySelector("#story-grid");
const dialog = document.querySelector(".story-dialog");
const filters = [...document.querySelectorAll("[data-category]")];

function renderStories() {
  const allStories = editions[activeIssue].stories;
  const stories = allStories
    .map((story, index) => ({ story, index }))
    .filter(
      ({ story }) => activeCategory === "all" || story[0] === activeCategory,
    );
  grid.innerHTML = stories
    .map(
      ({ story: [category, title, deck, author, time, art], index }) =>
        `<article class="story-card"><div class="story-image">${artwork(art, index)}<span class="image-number">FIG. ${String(index + 1).padStart(2, "0")}</span></div><div class="story-byline"><span>${category} / ${author}</span><span>${time} READ</span></div><h3><button type="button" data-story="${index}">${title}</button></h3><p>${deck}</p></article>`,
    )
    .join("");
  document.querySelector(".story-count").textContent =
    `${String(stories.length).padStart(2, "0")} ${stories.length === 1 ? "STORY" : "STORIES"}`;
  document.querySelector('[data-category="all"] span').textContent = String(
    allStories.length,
  ).padStart(2, "0");
  filters.forEach((button) => {
    const active = button.dataset.category === activeCategory;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
}

filters.forEach((button) =>
  button.addEventListener("click", () => {
    activeCategory = button.dataset.category;
    renderStories();
  }),
);
document.querySelector("#issue-select").addEventListener("change", (event) => {
  activeIssue = event.target.value;
  document.querySelector("[data-issue-label]").textContent =
    `ISSUE ${activeIssue} — ${editions[activeIssue].name}`;
  document.querySelector("[data-cover-intro]").textContent =
    editions[activeIssue].intro;
  renderStories();
});

grid.addEventListener("click", (event) => {
  const button = event.target.closest("[data-story]");
  if (!button) return;
  const [category, title, deck, author, time, , ...paragraphs] =
    editions[activeIssue].stories[Number(button.dataset.story)];
  document.querySelector(".dialog-meta").textContent =
    `ISSUE ${activeIssue} / ${category.toUpperCase()} / ${author.toUpperCase()} / ${time} READ`;
  document.querySelector("#dialog-title").textContent = title;
  document.querySelector(".dialog-deck").textContent = deck;
  document.querySelector(".dialog-body").replaceChildren(
    ...paragraphs.map((text) => {
      const paragraph = document.createElement("p");
      paragraph.textContent = text;
      return paragraph;
    }),
  );
  dialog.showModal();
  dialog.scrollTop = 0;
  document.body.classList.add("article-open");
});
document
  .querySelectorAll(".dialog-close")
  .forEach((button) => button.addEventListener("click", () => dialog.close()));
dialog.addEventListener("close", () =>
  document.body.classList.remove("article-open"),
);
dialog.addEventListener("click", (event) => {
  if (event.target === dialog) {
    const rect = dialog.getBoundingClientRect();
    if (
      event.clientX < rect.left ||
      event.clientX > rect.right ||
      event.clientY < rect.top ||
      event.clientY > rect.bottom
    )
      dialog.close();
  }
});
renderStories();
